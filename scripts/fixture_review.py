"""Writes tests/FIXTURE_REVIEW.md: for every fixture, header facts, then the first 10 raw holding
lines (as they appear in the filing) next to the row the parser produced from each, so the
expected output can be approved by eye. XML fixtures show the first 10 <infoTable> blocks collapsed."""
import glob, gzip, os, re, sys
sys.path.insert(0, ".")
import pandas as pd
from pipeline.parse13f import parse_submission, split_submission, html_to_lines, parse_text_lines, _xml_root

N = 10
out = ["# Fixture review", "", "Generated by scripts/fixture_review.py. For each fixture: what the parser recorded, then the first",
       f"{N} raw holding lines beside the parsed row. `cusip` is as parsed (before cusip.py resolution).", ""]
paths = sorted(glob.glob("tests/fixtures/*.txt.gz"))
out.append(f"{len(paths)} fixtures.\n")
for path in paths:
    name = os.path.basename(path).replace(".txt.gz", "")
    text = gzip.open(path).read().decode("utf-8", "replace")
    p = parse_submission(text)
    out.append(f"## {name}")
    out.append(f"- manager: {p.manager_name} | form {p.form_type} | period {p.period_of_report} | report type: {p.report_type or '(blank)'}")
    out.append(f"- parse method **{p.parse_method}** | rows parsed **{p.n_rows}** | declared entry total **{p.entry_total}** | "
               f"value sum {p.value_sum:,} | declared value total {p.value_total if p.value_total is None else format(p.value_total, ',')}")
    out.append(f"- checksum entries ok: {p.checksum_entries_ok} | value ok: {p.checksum_value_ok} | cusip-bearing lines: {p.n_cusip_lines}")
    if p.notes:
        out.append(f"- notes: {' || '.join(p.notes)}")
    if p.errors:
        out.append(f"- errors: {' || '.join(p.errors)}")
    out.append("")
    header, docs = split_submission(text)
    if p.parse_method == "xml":
        xml = [d for d in docs if d["type"].upper().startswith("INFORMATION TABLE")][0]["text"]
        root = _xml_root(xml)
        for i, it in enumerate(root.xpath(".//*[local-name()='infoTable']")[:N]):
            raw = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "|", __import__("lxml.etree", fromlist=["tostring"]).tostring(it, encoding="unicode"))).strip("| ")
            raw = re.sub(r"\|+", " | ", raw)
            r = p.holdings.iloc[i]
            out.append(f"RAW   {raw[:230]}")
            out.append(f"ROW   cusip={r['cusip']} value={r['value']} shares={r['shares']} {r['sh_prn']} {r['put_call']} {r['investment_discretion']} | {r['name_of_issuer']} / {r['title_of_class']}")
            out.append("")
    else:
        main = [d for d in docs if d["type"].startswith("13F")] or docs
        for d in main:
            if re.search(r"Content-Transfer-Encoding:\s*quoted-printable", d["text"][:3000], re.I):
                import quopri
                d["text"] = quopri.decodestring(d["text"].encode("latin-1", "replace")).decode("latin-1")
        text_all = "\n".join(d["text"] for d in main)
        if re.search(r"<(html|tr|td)\b", text_all, re.I):
            lines = []
            for d in main:
                lines.extend(html_to_lines(d["text"]))
        else:
            lines = []
            for d in main:
                lines.extend(re.sub(r"<[^>]+>", "", d["text"]).splitlines())
        h, _ = parse_text_lines(lines, keep_source=True)
        if any("stacked-cell" in n for n in p.notes):
            # one cell per line: show the raw table area as a block, then the parsed rows
            from pipeline.parse13f import _is_cusip_only, _digits_are_ids
            dok = _digits_are_ids(lines)
            first = next(i for i, l in enumerate(lines) if _is_cusip_only(l, dok))
            nb = [l.rstrip() for l in lines[max(0, first - 36): first + 40] if l.strip()]
            out.append("RAW (stacked cells, first lines of the table area, one cell per line):")
            out.append("    " + " ¦ ".join(x.strip()[:28] for x in nb[:60]))
            out.append("")
            for _, r in p.holdings.head(N).iterrows():
                out.append(f"ROW   cusip={r['cusip']} value={r['value']} shares={r['shares']} {r['sh_prn']} {r['put_call']} {r['investment_discretion']} | {r['name_of_issuer']} / {r['title_of_class']}")
            out.append("")
            out.append("")
            continue
        if h.empty:
            # show what the table area looks like so the reviewer sees why nothing parsed
            cand = [l for l in lines if re.search(r"[0-9A-Z]{6}[0-9A-Z]{3}", l.upper()) and l.strip()]
            out.append("(no rows parsed) first raw lines containing a 9-char id:")
            for l in cand[:N]:
                out.append(f"RAW   {l.rstrip()[:230]}")
            out.append("")
        for _, r in h.head(N).iterrows():
            out.append(f"RAW   {r['_src'].rstrip()[:230]}")
            out.append(f"ROW   cusip={r['cusip']} value={r['value']} shares={r['shares']} {r['sh_prn']} {r['put_call']} {r['investment_discretion']} | {r['name_of_issuer']} / {r['title_of_class']}")
            out.append("")
    out.append("")
open("tests/FIXTURE_REVIEW.md", "w").write("\n".join(out))
print("wrote tests/FIXTURE_REVIEW.md", len(paths), "fixtures")
